"""G17: does a VLIW organisation with four parallel units that are also the spares buy speed?

Part 1 measures. It runs each workload on the golden core with the sliced ALU, schedules the real
instruction trace on 1 to 4 K-bit units (build/radslice_vliw) and reports the speedup.

Part 2 is a model. The four units are also spares, so a unit found dead costs width instead of the
chip. Three designs of the same four units are compared with one unit and no spare, on expected
throughput per unit of silicon, with the register file's ports scaled by width.

  E1  speedup per workload, K = 8, 16, 32, in-order and reordered issue (measured)
  E2  designs: 1 active + 3 spares / 4 active, graceful / 4 active, all must work / 1 unit, no spare
  E3  sensitivity: port area per extra unit, issue mode, K

Tier-C inputs (config/params.toml): unit count, port area fraction, one-unit register-file yield.
The unit yield is the marginal slice yield p = 0.71 (tier B) raised to K/8, as everywhere else.

Usage (repo root, after building):   python scripts/vliw_study.py [--out DIR] [--max-steps N]
"""
import argparse
import csv
import re
import subprocess
import sys
from math import comb
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "python"))
from radslice import cost_model as cost  # noqa: E402
from radslice.params import load_params  # noqa: E402

PARAMS = load_params()
P = PARAMS["yield.p_slice_good"].value
UNITS = int(PARAMS["vliw.units"].value)
PORT_FRAC = PARAMS["vliw.port_area_frac"].value
RF_YIELD_1 = PARAMS["vliw.rf_yield_one_unit"].value
KS = (8, 16, 32)
WORKLOADS = {"alu_mix": "alu_mix.elf", "chacha20": "workloads/chacha20.elf", "coremark_like": "workloads/coremark_like.elf"}
MODES = ("inorder", "reorder")
RF_T = cost.RF_PRIMARIES * cost.T_RF_BLOCK


def run_trace(build, elf, k, max_steps):
    exe = build / "radslice_vliw.exe"
    if not exe.exists():
        exe = build / "radslice_vliw"
    res = subprocess.run([str(exe), "--k", str(k), "--max-steps", str(max_steps), str(build / elf)],
                         capture_output=True, text=True, check=False)
    line = next((l for l in res.stderr.splitlines() if l.startswith("RADSLICE_VLIW")), None)
    if line is None:
        raise SystemExit(f"no RADSLICE_VLIW line from {elf} k={k}:\n{res.stderr[-400:]}")
    kv = dict(re.findall(r"(\w+)=(\d+)", line))
    return {key: int(v) for key, v in kv.items()}, "PASS" in res.stderr


def speedups(trace, mode):
    base = trace["w1_inorder"]
    return [base / trace[f"w{n}_{mode}"] for n in range(1, UNITS + 1)]


def rf_area(width, frac):
    return 1.0 + frac * (width - 1)


def design_rows(k, s, frac, rf_y1=RF_YIELD_1):
    """Four designs for one K and one speedup curve s[0..3] (speedup with 1..4 good units)."""
    u = P ** (k / 8.0)
    unit_t = cost.alu_unit_T(k)
    pgood = [comb(UNITS, n) * u ** n * (1 - u) ** (UNITS - n) for n in range(UNITS + 1)]

    def rf_y(width):
        return rf_y1 ** rf_area(width, frac)

    def silicon(width, units):
        return RF_T * rf_area(width, frac) + units * unit_t

    rows = {
        "1 unit, no spare":        (rf_y(1) * u * s[0], rf_y(1) * u, silicon(1, 1)),
        "1 active + 3 spares":     (rf_y(1) * (1 - pgood[0]) * s[0], rf_y(1) * (1 - pgood[0]), silicon(1, UNITS)),
        "4 active, graceful":      (rf_y(UNITS) * sum(pgood[n] * s[n - 1] for n in range(1, UNITS + 1)),
                                    rf_y(UNITS) * (1 - pgood[0]), silicon(UNITS, UNITS)),
        "4 active, all must work": (rf_y(UNITS) * pgood[UNITS] * s[UNITS - 1], rf_y(UNITS) * pgood[UNITS], silicon(UNITS, UNITS)),
    }
    base = rows["1 unit, no spare"]
    base_merit = base[0] / base[2]
    return {name: dict(throughput=t, chip_yield=y, silicon=si, merit=(t / si) / base_merit)
            for name, (t, y, si) in rows.items()}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "results"))
    ap.add_argument("--build", default=str(ROOT / "build"))
    ap.add_argument("--max-steps", type=int, default=20_000_000)
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    build = Path(args.build)

    traces = {}
    for name, elf in WORKLOADS.items():
        for k in KS:
            traces[(name, k)] = run_trace(build, elf, k, args.max_steps)

    md = ["# G17: four parallel units that are also the spares", "",
          "Generated by `scripts/vliw_study.py`. Part 1 is measured on the real instruction traces with a fault-free "
          "sliced ALU; part 2 is a model whose inputs are tier C. Nothing here is a chip measurement.", "",
          f"Steps per workload: {args.max_steps:,} (a workload that did not finish is marked `budget`).", "",
          "## E1  Speedup from 1 to 4 units (measured on the trace)", "",
          "Speedup over one unit issuing in order, which is `instret x base + beats`. A dependent chain cannot use "
          "more units; the block barrier is a branch, jump or system instruction; no speculation.", "",
          "| workload | K | mode | 1 | 2 | 3 | 4 | status |", "|---|---|---|---|---|---|---|---|"]
    csv_rows = []
    for (name, k), (tr, done) in traces.items():
        for mode in MODES:
            s = speedups(tr, mode)
            md.append(f"| {name} | {k} | {mode} | " + " | ".join(f"{v:.2f}" for v in s) + f" | {'done' if done else 'budget'} |")
            csv_rows.append(dict(part="E1", workload=name, k=k, mode=mode, **{f"speedup_{n + 1}": f"{v:.4f}" for n, v in enumerate(s)}))

    def mean_curve(k, mode):
        curves = [speedups(traces[(w, k)][0], mode) for w in WORKLOADS]
        return [sum(c[i] for c in curves) / len(curves) for i in range(UNITS)]

    md += ["", "## E2  Designs of the same four units (mean speedup of the three workloads)", "",
           f"Unit yield is p^(K/8) with p = {P}. Register file: one-unit yield {RF_YIELD_1}, scaled by area "
           f"(1 + {PORT_FRAC} per extra unit) as y^area. Merit = throughput per unit of silicon, relative to one "
           "unit with no spare. Throughput per fabricated chip counts a dead chip as 0.", ""]
    for k in KS:
        md += [f"### K = {k}  (unit yield {P ** (k / 8):.3f})", "",
               "| design | issue | throughput per chip | chip yield | silicon (x one-unit chip) | merit |", "|---|---|---|---|---|---|"]
        for mode in MODES:
            rows = design_rows(k, mean_curve(k, mode), PORT_FRAC)
            one_si = rows["1 unit, no spare"]["silicon"]
            for name, r in rows.items():
                md.append(f"| {name} | {mode} | {r['throughput']:.3f} | {r['chip_yield']:.3f} | {r['silicon'] / one_si:.3f} | {r['merit']:.2f} |")
                csv_rows.append(dict(part="E2", k=k, mode=mode, design=name, throughput=f"{r['throughput']:.5f}",
                                     chip_yield=f"{r['chip_yield']:.5f}", silicon=f"{r['silicon']:.1f}", merit=f"{r['merit']:.4f}"))
        md.append("")

    md += ["## E3  Sensitivity: register-file area per extra unit", "",
           "Merit of the graceful four-unit design (reordered issue) as the port area grows. Below 1.00 the extra "
           "units cost more than they return.", "", "| K | " + " | ".join(f"area {f:g}" for f in (0.0, 0.15, 0.30, 0.6, 1.0)) + " |",
           "|---|" + "---|" * 5]
    crossover = {}
    for k in KS:
        cells = []
        for f in (0.0, 0.15, 0.30, 0.6, 1.0):
            m = design_rows(k, mean_curve(k, "reorder"), f)["4 active, graceful"]["merit"]
            cells.append(f"{m:.2f}")
            csv_rows.append(dict(part="E3", k=k, mode="reorder", design="4 active, graceful", port_area=f, merit=f"{m:.4f}"))
        md.append(f"| {k} | " + " | ".join(cells) + " |")
        lo, hi = 0.0, 4.0
        for _ in range(40):
            mid = (lo + hi) / 2
            if design_rows(k, mean_curve(k, "reorder"), mid)["4 active, graceful"]["merit"] >= 1.0:
                lo = mid
            else:
                hi = mid
        crossover[k] = lo
    md += ["", "Port area per extra unit at which the graceful four-unit design stops beating one unit with no spare "
           "(reordered issue): " + ", ".join(f"K = {k}: {v:.2f}" for k, v in crossover.items()) + ".", ""]

    (out / "vliw_study.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    fields = sorted({key for r in csv_rows for key in r}, key=lambda s: (s != "part", s))
    with open(out / "vliw_study.csv", "w", newline="", encoding="utf-8") as fh:
        wr = csv.DictWriter(fh, fieldnames=fields)
        wr.writeheader()
        wr.writerows(csv_rows)
    print("\n".join(md))


if __name__ == "__main__":
    main()
