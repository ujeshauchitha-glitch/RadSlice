"""G19 step 1: a small int8 digit classifier and its integer reference (the golden answer for the MAC array).

Trains a 64-32-10 network on scikit-learn's bundled 8x8 digits (no download), quantizes it to int8 weights
with int32 accumulators and a power-of-two requantization shift, and writes:
  results/g19_network.npz   weights, biases, shifts, and the held-out test set
  results/g19_baseline.md   fault-free accuracy of the float and the integer network

The integer forward pass here is the reference the Verilog array is later checked against bit for bit.
"""
import os
import numpy as np
from sklearn.datasets import load_digits
from sklearn.model_selection import train_test_split
from sklearn.neural_network import MLPClassifier

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IN, HID, OUT = 64, 32, 10
SEED = 1


def quantize_weights(w):
    """Symmetric int8: returns (int8 matrix, scale) with w ~ q * scale."""
    scale = np.abs(w).max() / 127.0
    return np.clip(np.round(w / scale), -127, 127).astype(np.int8), scale


def int_forward(x_u7, w1, b1, shift1, w2, b2):
    """Integer reference. x_u7: (n, 64) ints in 0..127. Returns (hidden int8-range ints, logits int32)."""
    acc1 = x_u7.astype(np.int32) @ w1.astype(np.int32).T + b1.astype(np.int32)
    h = np.clip(acc1 >> shift1, 0, 127).astype(np.int32)  # ReLU and requantize in one clip
    logits = h @ w2.astype(np.int32).T + b2.astype(np.int32)
    return h, logits


def main():
    d = load_digits()
    x = np.round(d.data * 7).astype(np.int32)  # pixel 0..16 -> 0..112, fits a signed int8
    y = d.target
    xtr, xte, ytr, yte = train_test_split(x, y, test_size=0.3, random_state=SEED, stratify=y)

    clf = MLPClassifier(hidden_layer_sizes=(HID,), activation="relu", max_iter=600, random_state=SEED)
    clf.fit(xtr / 112.0, ytr)
    acc_float = clf.score(xte / 112.0, yte)

    # The float network works on x/112, so the integer network's first layer sees x = 112 * x_float.
    w1f = clf.coefs_[0].T  # (HID, IN)
    w2f = clf.coefs_[1].T  # (OUT, HID)
    q1, s1 = quantize_weights(w1f)
    q2, s2 = quantize_weights(w2f)
    # acc1 = sum(x_int * q1) + b1 with x_int = 112 * x_float, so one accumulator step is s1 / 112 of a float unit.
    b1 = np.round(clf.intercepts_[0] * 112.0 / s1).astype(np.int64)
    # Pick the requantization shift so the hidden activations use most of 0..127 on the training set.
    acc_probe = xtr.astype(np.int64) @ q1.astype(np.int64).T + b1
    peak = np.percentile(np.maximum(acc_probe, 0), 99.5)
    shift1 = max(0, int(np.ceil(np.log2(max(peak, 1) / 127.0))))
    # After the shift, one hidden step is 2^shift1 accumulator steps, i.e. h_unit float units.
    h_unit = (2 ** shift1) * s1 / 112.0
    b2 = np.round(clf.intercepts_[1] / (s2 * h_unit)).astype(np.int64)

    _, logits = int_forward(xte, q1, b1, shift1, q2, b2)
    acc_int = float((logits.argmax(1) == yte).mean())
    agree = float((logits.argmax(1) == clf.predict(xte / 112.0)).mean())

    os.makedirs(os.path.join(ROOT, "results"), exist_ok=True)
    np.savez(os.path.join(ROOT, "results", "g19_network.npz"), w1=q1, b1=b1, shift1=shift1, w2=q2, b2=b2,
             xte=xte, yte=yte)
    macs = IN * HID + HID * OUT
    md = f"""# G19 step 1: the quantized digit classifier (fault-free)

Network 64-{HID}-10 on scikit-learn's bundled 8x8 digits, {len(xtr)} training and {len(xte)} held-out images
(seed {SEED}). int8 weights, int32 accumulators, hidden activations clipped to 0..127 after a shift of {shift1} bits.

| | held-out accuracy |
|---|---|
| float network | {acc_float:.4f} |
| integer network (the reference for the array) | {acc_int:.4f} |

The integer network agrees with the float network's prediction on {agree:.4f} of the held-out images.
Multiply-accumulates per image: {macs}. Weights: {macs} bytes plus {HID + OUT} biases.
Generated by `scripts/g19_reference.py`; nothing here is a measurement of any chip.
"""
    with open(os.path.join(ROOT, "results", "g19_baseline.md"), "w", encoding="utf-8") as f:
        f.write(md)
    print(md)
    print("shift1", shift1, "b1 range", b1.min(), b1.max(), "b2 range", b2.min(), b2.max())


if __name__ == "__main__":
    main()
